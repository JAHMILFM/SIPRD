-- Las dos entidades migradas con ID corporativo requieren generación para nuevos registros locales.
DO $$
DECLARE t text; col text; seq text;
BEGIN
 FOR t,col IN VALUES ('pedidos','id_pedido'),('paradas_ruta','id_parada') LOOP
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='siprd' AND table_name=t AND column_name=col AND is_identity='NO' AND column_default IS NULL) THEN
   EXECUTE format('ALTER TABLE siprd.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',t,col);
   seq:=pg_get_serial_sequence('siprd.'||t,col);
   EXECUTE format('SELECT setval(%L,COALESCE(MAX(%I),0)+1,false) FROM siprd.%I',seq,col,t);
  END IF;
 END LOOP;
END $$;

